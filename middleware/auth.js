const jwt = require('jsonwebtoken');
const { UserRepository } = require('../models/User');

const protect = async (req, res, next) => {
  let token;
  if (req.headers.authorization && req.headers.authorization.startsWith('Bearer')) {
    token = req.headers.authorization.split(' ')[1];
  } else if (req.cookies && req.cookies.token) {
    token = req.cookies.token;
  }

  if (!token) {
    return res.status(401).json({ message: 'Not authorized, no session token provided' });
  }

  try {
    const decoded = jwt.verify(token, process.env.JWT_SECRET || 'devflow_jwt_secret_key_987654321');
    const user = await UserRepository.findById(decoded.id);

    if (!user) {
      return res.status(401).json({ message: 'User account not found or deleted' });
    }

    req.user = user;
    next();
  } catch (error) {
    return res.status(401).json({ message: 'Not authorized, invalid or expired token' });
  }
};

const adminOnly = (req, res, next) => {
  if (req.user && req.user.role === 'admin') {
    next();
  } else {
    res.status(403).json({ message: 'Access denied: Admin privileges required' });
  }
};

module.exports = { protect, adminOnly };
